from functools import reduce

def chinese_remainder(moduli, remainders):
    prod = reduce(lambda a, b: a * b, moduli)
    total = 0
    for n_i, a_i in zip(moduli, remainders):
        p = prod // n_i
        total += a_i * pow(p, -1, n_i) * p
    return total % prod

